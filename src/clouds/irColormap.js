const entries = [];
for (const pair of TABLE.split(';')) {
  const [rgb, t] = pair.split(':');
  const [r, g, b] = rgb.split(',').map(Number);
  entries.push([r, g, b, Number(t)]);
}
for (const [v, t] of GREYS) entries.push([v, v, v, t]);

const exact = new Map(entries.map(([r, g, b, t]) => [(r << 16) | (g << 8) | b, t]));
const nearestCache = new Map();

/** RGB → brightness temperature (°C). Unknown colours (resampling blends) snap to the nearest entry. */
export function rgbToCelsius(r, g, b) {
  const key = (r << 16) | (g << 8) | b;
  let t = exact.get(key);
  if (t !== undefined) return t;
  t = nearestCache.get(key);
  if (t !== undefined) return t;
  let best = Infinity;
  for (const [er, eg, eb, et] of entries) {
    const d = (er - r) ** 2 + (eg - g) ** 2 + (eb - b) ** 2;
    if (d < best) {
      best = d;
      t = et;
    }
  }
  nearestCache.set(key, t);
  return t;
}
